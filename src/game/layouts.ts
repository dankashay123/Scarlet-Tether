/** Normalise row widths (pad with wall) so hand-typed maps can't break the grid. */
export function normalise(l: Layout): Layout {
  const w = Math.max(...l.rows.map((r) => r.length));
  return { ...l, rows: l.rows.map((r) => (r.length < w ? r + '#'.repeat(w - r.length) : r)) };
}
