export const FONT = 'font';
export const FONT_OUTLINE = 'font-o';
const CELL_H = 8;
export const FONT_LINE_HEIGHT = 10;

function buildFont(scene: Phaser.Scene, key: string, outlined: boolean) {
  const chars = Object.keys(GLYPHS);
  const pad = outlined ? 1 : 0;
  const cellW = 6 + pad * 2;
  const cellH = CELL_H + pad * 2;
  const cols = 16;
  const rows = Math.ceil((chars.length + 1) / cols);
  const pc = new PixelCanvas(cols * cellW, rows * cellH);
  const metrics: { ch: string; x: number; y: number; w: number }[] = [];

  chars.forEach((ch, idx) => {
    const rowsStr = GLYPHS[ch].split('|');
    const w = Math.max(...rowsStr.map((r) => r.length));
    const ox = (idx % cols) * cellW;
    const oy = Math.floor(idx / cols) * cellH;
    const glyph = new PixelCanvas(w + pad * 2, cellH);
    rowsStr.forEach((r, y) => {
      for (let x = 0; x < r.length; x++) if (r[x] === '#') glyph.px(x + pad, y + pad, '#ffffff');
    });
    if (outlined) glyph.outline('#0b0507', true);
    pc.blit(glyph, ox, oy);
    metrics.push({ ch, x: ox, y: oy, w });
  });

  if (scene.textures.exists(key)) scene.textures.remove(key);
  const tex = scene.textures.addCanvas(key, pc.toCanvas())!;
  const frame = tex.get();
  const tw = pc.w;
  const th = pc.h;

  // Phaser's runtime reads xAdvance/kerning/data though its typings omit them.
  type CharData = Phaser.Types.GameObjects.BitmapText.BitmapFontCharacterData & { xAdvance: number; data: object; kerning: object };
  const data = {
    font: key,
    size: CELL_H,
    lineHeight: FONT_LINE_HEIGHT,
    retroFont: false,
    chars: {} as Record<number, CharData>,
  };
  const mk = (x: number, y: number, w: number, h: number, adv: number): CharData => ({
    x,
    y,
    width: w,
    height: h,
    centerX: Math.floor(w / 2),
    centerY: Math.floor(h / 2),
    xOffset: -pad,
    yOffset: -pad,
    xAdvance: adv,
    data: {},
    kerning: {},
    u0: (frame.cutX + x) / tw,
    v0: (frame.cutY + y) / th,
    u1: (frame.cutX + x + w) / tw,
    v1: (frame.cutY + y + h) / th,
  });
  for (const m of metrics) {
    const gw = m.w + pad * 2;
    data.chars[m.ch.charCodeAt(0)] = mk(m.x, m.y, gw, cellH, m.w + 1);
    tex.add(m.ch, 0, m.x, m.y, gw, cellH);
  }
  // Space: an empty 1px glyph with a 3px advance.
  data.chars[32] = mk(0, 0, 0, 0, 3);
  scene.cache.bitmapFont.add(key, { data, texture: key, frame: null });
}

export function buildFonts(scene: Phaser.Scene) {
  buildFont(scene, FONT, false);
  buildFont(scene, FONT_OUTLINE, true);
}
